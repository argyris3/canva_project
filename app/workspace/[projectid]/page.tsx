"use client"
import SmartDoc from '@/components/custom/workspace/SmartDoc'
import Whiteboard from '@/components/custom/workspace/Whiteboard'
import WorkspaceHeader from '@/components/custom/workspace/WorkspaceHeader'
import { ExcalidrawImperativeAPI } from '@excalidraw/excalidraw/types'
import axios from 'axios'
import { useParams } from 'next/navigation'
import React, { useEffect, useRef, useState } from 'react'

const normalizeAppState = (appState: Record<string, any> | null | undefined) => {
    if (!appState || typeof appState !== 'object') {
        return {}
    }

    // Excalidraw expects collaborators to be iterable; persisted JSON may not preserve that shape.
    const normalizedCollaborators = Array.isArray(appState.collaborators)
        ? appState.collaborators
        : []

    return {
        ...appState,
        collaborators: normalizedCollaborators
    }
}

function Workspace() {
    const [avctiveTab, setActiveTab] = useState('whiteboard')
    const [api, setApi] = useState<ExcalidrawImperativeAPI | null>(null)
    const [projectName, setProjectName] = useState('');
    const [isShareable, setIsShareable] = useState(false);
    const [canEdit, setCanEdit] = useState(false);
    const [loadError, setLoadError] = useState('');
    const saveWhiteboardRef = useRef<(() => Promise<void>) | null>(null)
    const { projectid } = useParams();

    useEffect(() => {
        // Wait for both the route id and Excalidraw API before hydrating the scene.
        projectid && api && GetWhiteboardData();
    }, [projectid, api]);

    const GetWhiteboardData = async () => {
        try {
            const result = await axios.get(
                "/api/projects?projectId=" + projectid
            );

            console.log("Whiteboard Data:", result.data);
            setProjectName(result?.data?.projectName)
            setIsShareable(result?.data?.isShareable === true)
            setCanEdit(result?.data?.canEdit === true)
            setLoadError('')
            // Shadows are regenerated by the client UI and should not be restored as real canvas content.
            const elementsWithoutNoteShadows = (result.data.elements || []).filter((element: any) => {
                return element.customData?.type !== "floating-note-shadow"
            })

            api?.updateScene({
                elements: elementsWithoutNoteShadows,
                appState: normalizeAppState(result.data.appState)
            })

            if (result.data.files) {
                // Image elements reference files separately, so reattach saved file blobs after scene restore.
                api?.addFiles(
                    Object.values(result.data.files)
                )
            }

        } catch (error) {
            console.error("Failed to load whiteboard:", error);
            setLoadError('This project is private or unavailable.')
        }
    }

    const handleExportImage = async () => {
        if (!api) return;

        // Export from the live scene so manual changes are included even before the next autosave.
        const { exportToBlob } = await import('@excalidraw/excalidraw')
        const blob = await exportToBlob({
            elements: api.getSceneElements(),
            appState: {
                ...api.getAppState(),
                exportBackground: true
            },
            files: api.getFiles(),
            mimeType: "image/png",
            quality: 1
        });

        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = 'whiteboard.png',
            link.click();

        URL.revokeObjectURL(url);
    }
    return (
        <div>
            <WorkspaceHeader
                selectedTab={(value: string) => setActiveTab(value)}
                onExport={() => handleExportImage()}
                onSave={() => saveWhiteboardRef.current?.()}
                projectName={projectName}
                projectId={String(projectid ?? '')}
                isShareable={isShareable}
                canEdit={canEdit}
                onShareableChange={(value) => setIsShareable(value)}
            />

            {loadError && (
                <div className='flex h-[70vh] items-center justify-center px-6 text-center text-sm text-muted-foreground'>
                    {loadError}
                </div>
            )}

            {!loadError && (avctiveTab == 'whiteboard' ?
                (
                    // Whiteboard registers its imperative API and save callback back up to this route shell.
                    <Whiteboard
                        onApiReady={(api) => setApi(api)}
                        onSaveReady={(saveWhiteboard) => {
                            saveWhiteboardRef.current = saveWhiteboard
                        }}
                        readOnly={!canEdit}
                    />
                ) : <SmartDoc />
            )}
        </div>
    )
}

export default Workspace
